-- =====================================================================
-- TRILHA+ — Script SQL do banco de dados (PostgreSQL)
-- Gerado a partir do banco criado pelo Hibernate (pg_dump) e organizado para leitura.
-- Cria as 14 tabelas, chaves primárias, chaves estrangeiras e restrições.
--
-- Uso:  psql -U postgres -d trilha_mais -f backend/database/schema.sql
-- Pode rodar mais de uma vez (IF NOT EXISTS). O back-end também cria tudo sozinho
-- ao subir (spring.jpa.hibernate.ddl-auto=update).
-- Os DEFAULTs abaixo repetem os valores padrão das entidades Java, para facilitar inserts manuais.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- Estudantes
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password      VARCHAR(255) NOT NULL,              -- hash BCrypt, nunca texto puro
    streak_days   INTEGER      NOT NULL DEFAULT 0,    -- sequência de dias seguidos de estudo
    avatar_emoji  VARCHAR(20)           DEFAULT '🎓'
);

-- ---------------------------------------------------------------------
-- Matérias, assuntos e materiais
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS subjects (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(255)  NOT NULL,
    description    VARCHAR(1000),
    color_key      VARCHAR(50),                       -- portugues, matematica, historia, biologia...
    primary_color  VARCHAR(20),                       -- ex.: #2563EB
    icon           VARCHAR(20),                       -- emoji
    user_id        BIGINT        NOT NULL REFERENCES users(id),
    created_at     TIMESTAMP(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS topics (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255)  NOT NULL,
    description  VARCHAR(1000),
    status       VARCHAR(30)   NOT NULL DEFAULT 'pendente',   -- pendente | andamento | concluido
    subject_id   BIGINT        NOT NULL REFERENCES subjects(id),
    created_at   TIMESTAMP(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS study_materials (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(255) NOT NULL,
    content     TEXT         NOT NULL,
    type        VARCHAR(30)  NOT NULL DEFAULT 'NOTES'
                CHECK (type IN ('SUMMARY', 'NOTES', 'TEXT', 'ARTICLE')),
    topic_id    BIGINT       NOT NULL REFERENCES topics(id),
    created_at  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------
-- Banco de questões
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS questions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text         TEXT         NOT NULL,
    explanation  TEXT,
    topic_id     BIGINT       NOT NULL REFERENCES topics(id),
    created_at   TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS question_options (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text         VARCHAR(255) NOT NULL,
    is_correct   BOOLEAN      NOT NULL,
    question_id  BIGINT       NOT NULL REFERENCES questions(id)
);

-- ---------------------------------------------------------------------
-- Simulados (quiz)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS quizzes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(255)     NOT NULL,
    user_id          BIGINT           NOT NULL REFERENCES users(id),
    topic_id         BIGINT           REFERENCES topics(id),     -- simulado de um assunto
    subject_id       BIGINT           REFERENCES subjects(id),   -- ou de uma matéria inteira
    total_questions  INTEGER          NOT NULL,
    correct_answers  INTEGER,
    score            DOUBLE PRECISION,                           -- nota de 0 a 10
    status           VARCHAR(255)     NOT NULL DEFAULT 'IN_PROGRESS'
                     CHECK (status IN ('IN_PROGRESS', 'COMPLETED')),
    created_at       TIMESTAMP(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at     TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS quiz_questions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id      BIGINT  NOT NULL REFERENCES quizzes(id),
    question_id  BIGINT  NOT NULL REFERENCES questions(id),
    order_index  INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS quiz_answers (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id             BIGINT  NOT NULL REFERENCES quizzes(id),
    question_id         BIGINT  NOT NULL REFERENCES questions(id),
    selected_option_id  BIGINT  REFERENCES question_options(id),  -- NULL = não respondeu
    is_correct          BOOLEAN NOT NULL
);

-- ---------------------------------------------------------------------
-- Agenda
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS schedules (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(255) NOT NULL,
    subject_name    VARCHAR(255),
    color_key       VARCHAR(50),
    icon            VARCHAR(20),
    scheduled_date  DATE,                              -- data real do compromisso
    days_ahead      INTEGER               DEFAULT 0,   -- recalculado pela API a partir da data
    scheduled_time  VARCHAR(10),                       -- ex.: '14:00'
    completed       BOOLEAN      NOT NULL DEFAULT FALSE,
    user_id         BIGINT       NOT NULL REFERENCES users(id),
    subject_id      BIGINT       REFERENCES subjects(id) ON DELETE SET NULL,
    topic_id        BIGINT       REFERENCES topics(id)   ON DELETE SET NULL,
    created_at      TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------
-- Sequência de estudos, recuperação de senha, configurações e chat
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS study_activities (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    activity_date  DATE        NOT NULL,
    activity_type  VARCHAR(30) NOT NULL
                   CHECK (activity_type IN ('QUIZ', 'TOPIC', 'SCHEDULE', 'CHAT')),
    UNIQUE (user_id, activity_date, activity_type)    -- cada tipo conta 1 vez por dia
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash  VARCHAR(64)  NOT NULL,                 -- SHA-256 do código de 6 dígitos
    expires_at  TIMESTAMP(6) NOT NULL,                 -- 30 minutos após o pedido
    used_at     TIMESTAMP(6),
    attempts    INTEGER      NOT NULL DEFAULT 0,       -- máximo de 5 tentativas
    created_at  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_settings (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT      NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    notifications_enabled  BOOLEAN     NOT NULL DEFAULT TRUE,
    theme                  VARCHAR(10) NOT NULL DEFAULT 'light'   -- light | dark
);

CREATE TABLE IF NOT EXISTS chat_messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    subject_id  BIGINT       REFERENCES subjects(id) ON DELETE SET NULL,
    role        VARCHAR(10)  NOT NULL,                 -- user | assistant
    content     TEXT         NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMIT;
